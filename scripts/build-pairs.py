#!/usr/bin/env python3
"""Build data/pairs.json (daily verb cards) and data/vocab.json (Word Bank)
from scripts/verbs.py. Romanization is generated by scripts/romanize.py.
Run: python3 scripts/build-pairs.py && python3 scripts/generate-audio.py"""
import json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from romanize import ko as ro_ko, tl as ro_tl
from verbs import VERBS, parse_vocab

ROOT = Path(__file__).resolve().parent.parent
LANG = {"korean": ("ko", ro_ko), "tagalog": ("tl", ro_tl)}

def slug(lang, base):
    r = (ro_ko(base) if lang == "ko" else ro_tl(base)).replace(" ", "_")
    return f"{lang}-{re.sub(r'[^a-z0-9_-]', '', r.lower())}"

pairs, vocab, seen_text = [], {}, {}
for vid, en, kw, kd, tw, tstress, td, sents in VERBS:
    card = {"id": vid, "english": en,
            "korean": {"word": kw, "romanization": ro_ko(kw), "definition": kd, "examples": []},
            "tagalog": {"word": tw, "romanization": tstress, "definition": td, "examples": []}}
    for n, (gloss, tense, kt, kh, kv, tt, th, tv) in enumerate(sents):
        for key, text, hl, spec in (("korean", kt, kh, kv), ("tagalog", tt, th, tv)):
            code, ro = LANG[key]
            assert hl in text, (vid, text, hl)
            ex = {"text": text, "romanization": ro(text), "highlight": hl, "en": gloss, "tense": tense, "vocab": []}
            clip = f"{vid}-ex{n+1}"
            if (code, text) in seen_text: ex["audioId"] = seen_text[(code, text)]
            else: seen_text[(code, text)] = clip
            for surface, base, ven, pos, start in parse_vocab(spec, text):
                k = (code, base)
                if k not in vocab:
                    sid = slug(code, base); taken = {x["id"] for x in vocab.values()}
                    while sid in taken: sid += "_"
                    vocab[k] = {"id": sid, "lang": key, "word": base, "romanization": ro(base),
                                "english": ven, "pos": pos, "sources": []}
                v = vocab[k]
                parts = [x.strip() for x in v["english"].split(";")]
                for x in ven.split(";"):
                    if x.strip() not in parts: parts.append(x.strip())
                v["english"] = "; ".join(parts)
                v["sources"].append({"verb": vid, "ex": n, "surface": surface})
                ex["vocab"].append({"surface": surface, "start": start, "id": v["id"]})
            card[key]["examples"].append(ex)
    pairs.append(card)

ids = [v["id"] for v in vocab.values()]
dups = {i for i in ids if ids.count(i) > 1}
assert not dups, dups
(ROOT / "data/pairs.json").write_text(json.dumps(pairs, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
(ROOT / "data/vocab.json").write_text(json.dumps(list(vocab.values()), ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print(len(pairs), "verbs,", sum(len(p["korean"]["examples"]) for p in pairs), "sentence pairs,", len(vocab), "vocab")
